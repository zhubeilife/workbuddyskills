#      「王五上周也迟到」里"王五"后面紧跟被屏蔽的"上"，会导致真名"王五"漏检（实测）。
WEEK_TIME_PREV = "上下本这那每两三四五六七八九十几多"
NEG_CONTEXT = ("退步", "没考好", "考砸", "落后", "下滑", "不交", "违纪", "批评", "扰乱",
               "打人", "作弊", "抄袭", "屡教不改", "不听话", "垫底", "倒数", "拖后腿")

# 反例说明区（v1.3）：话术卡里这些区块会**引用红线原句作为反面示例**
# （如「【不宜说】一是"我不做评价"……」），整块跳过，否则会把反例引用误判成真实违规。
EXEMPT_SECTION_KEYS = ("不宜说", "红线自检", "待补信息", "政策来源核对",
                       "反例", "原句", "修正", "注意事项", "自检")
SECTION_RE = re.compile(r"【\s*([^】\n]{1,20})\s*】")


def build_exempt_flags(lines):
    """逐行标记是否位于反例说明区；区块由最近出现的【…】小标题决定。"""
    flags, cur = [], ""
    for ln in lines:
        m = SECTION_RE.search(ln)
        if m:
            cur = m.group(1)
        flags.append(any(k in cur for k in EXEMPT_SECTION_KEYS))
    return flags


def is_negated(line, start, end=None, cat=None):
    """命中片段自身或其左侧若存在否定词，则属"不要怎么做"的正确表述，排除。
    end 传入命中片段结束位置，用于检测"家长不要每天批改作业"这类否定词嵌在片段内部的情形。
    cat 为规则类别名；"施压绑架"与 v1.3 新增的"元话语免责"两类本身就以否定式出现
    （如"不来的孩子可惜了""我不做评价"），故这两类不做否定排除，否则会漏掉真实红线。

    ⚠️ 否定判定**只在同一小句内有效**：左侧窗口若跨过逗号/句号等标点，则不认否定。
    否则「我们班考得不好，张三这次退步很大」里的"不好"会误把"张三"当成否定语境而漏检。
    """
    if cat in NO_NEG_EXEMPT_CATS:
        return False
    left = line[max(0, start - NEG_WINDOW):start]
    # 从最后一个句读边界之后重新计算——否定词不跨小句生效
    cut = 0
    for k, ch in enumerate(left):
        if ch in CLAUSE_BREAK:
            cut = k + 1
    left = left[cut:]
    if any(w in left for w in NEG_WORDS):
        return True
    if end is not None:
        seg = line[start:end]
        # 片段内部的否定词：命中片段本身含"不要/别/勿/无需/不得"
        # v1.6：「绝对承诺」豁免这一半（该分支天然带"不再／不会"，否则永不触发）。
        if cat not in SEG_NEG_EXEMPT_CATS and any(w in seg for w in NEG_WORDS):
            return True
    return False


def find_all(pat, text):
    return re.finditer(pat, text)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("text_file")
    args = ap.parse_args()
    if not os.path.isfile(args.text_file):
        print(json.dumps({"error": "文件不存在: %s" % args.text_file}, ensure_ascii=False))
        sys.exit(2)

    hits = []
    with open(args.text_file, encoding="utf-8") as f:
        lines = f.read().splitlines()
    exempt = build_exempt_flags(lines)
    for i, line in enumerate(lines, 1):
        if exempt[i - 1]:
            continue
        for cat, pat in RULES:
            for m in find_all(pat, line):
                if is_negated(line, m.start(), m.end(), cat):
                    continue
                hits.append({"category": cat, "pattern": pat, "matched": m.group(0),
                             "line": i,
                             "context": line[max(0, m.start() - 10): m.end() + 10]})

        # 真实姓名 + 负面语境（同句共现，且排除普通词）
        # v1.4：改为允许重叠的手动扫描——被否掉的位置只前进 1 字，
        #        这样「这周周明退步了」能在否掉"这周"后，从下一个"周"重新找到真名"周明"。
        if any(w in line for w in NEG_CONTEXT):
            pos = 0
            while True:
                nm = NAME_RE.search(line, pos)
                if not nm:
                    break
                seg = nm.group(0)
                if any(seg.startswith(s) for s in NAME_STOPWORDS):
                    pos = nm.start() + 1
                    continue
                # 排除「姓 + 常见虚字/动词」这种明显不是人名的组合
                if len(seg) == 2 and seg[1] in NAME_BAD_SUFFIX:
                    pos = nm.start() + 1
                    continue
                # v1.4：名字不会以虚字收尾（"周四和"）
                if seg[-1] in NAME_BAD_FINAL:
                    pos = nm.start() + 1
                    continue
                # v1.4：时间表达里的"周"不是姓氏（这两周／上周／下周三）
                if seg[0] == "周":
                    prev = line[nm.start() - 1] if nm.start() > 0 else ""
                    if prev in WEEK_TIME_PREV or WEEKDAY_RE.match(line, nm.start()):
                        pos = nm.start() + 1
                        continue
                if is_negated(line, nm.start(), nm.end()):
                    pos = nm.start() + 1
                    continue
                hits.append({"category": "姓名点名", "pattern": "<姓氏>+名+负面词",
                             "matched": seg, "line": i,
                             "context": line[max(0, nm.start() - 10): nm.end() + 12]})
                pos = nm.end()

    print(json.dumps({"total": len(hits), "hits": hits,
                      "summary": "红线检查通过" if not hits else "命中 %d 处，需改写后复检" % len(hits)},
                     ensure_ascii=False, indent=2))
    sys.exit(1 if hits else 0)


if __name__ == "__main__":
    main()
