def write_homework(rows, path, rng):
    wb = Workbook()
    ws = wb.active
    ws.title = "作业统计"
    ws.append(["学号", "姓名", "应交次数", "实交次数", "提交率", "按时提交率",
               "订正完成率", "作业质量等级", "备注"])
    for r in rows:
        if r["学号"] in MISSING_IN_TASK:
            continue
        due = 32
        rate = clamp(0.74 + r["总分"] / 640 + rng.uniform(-0.07, 0.07), 0.60, 1.0)
        done, on_time, fix, grade, note = None, rate - rng.uniform(0.02, 0.10), None, None, ""
        fix = clamp(rate - rng.uniform(0.02, 0.14), 0.55, 1.0)
        if r["学号"] in HOMEWORK_OVERRIDE:
            d, ot, fx, gr, nt = HOMEWORK_OVERRIDE[r["学号"]]
            done = d
            on_time = ot if ot is not None else on_time
            fix = fx if fx is not None else fix
            grade = gr
            note = nt
        if done is None:
            done = due - rng.choices([0, 1, 2, 3], weights=[62, 24, 10, 4])[0]
        if grade is None:
            grade = "A" if rate > 0.93 and fix > 0.88 else ("B" if rate > 0.85 else "C")
        ws.append([r["学号"], r["姓名"], due, done, round(done / due, 3),
                   round(on_time, 3), round(fix, 3), grade, note])
    style_head(ws, 9)
    wb.save(path)


def write_classroom(rows, path, rng):
    wb = Workbook()
    ws = wb.active
    ws.title = "课堂表现"
    ws.append(["学号", "姓名", "发言次数", "专注度", "小组合作", "课堂纪律", "课堂任务完成率"])
    for r in rows:
        if r["学号"] in MISSING_IN_TASK:
            continue
        lv = r["总分"] / 640
        speak = max(0, int(round(rng.gauss(4 + lv * 16, 5))))
        focus = round(clamp(3.4 + lv * 1.6 + rng.uniform(-0.4, 0.4), 1.5, 5.0), 1)
        coop = round(clamp(3.6 + lv * 1.3 + rng.uniform(-0.4, 0.4), 1.5, 5.0), 1)
        disc = round(clamp(3.8 + lv * 1.2 + rng.uniform(-0.5, 0.4), 1.5, 5.0), 1)
        task = round(clamp(0.68 + lv * 0.34 + rng.uniform(-0.06, 0.06), 0.5, 1.0), 3)
        if r["学号"] in CLASSROOM_OVERRIDE:
            speak, focus, coop, disc, task = CLASSROOM_OVERRIDE[r["学号"]]
        name = CLASSROOM_TYPO.get(r["学号"], r["姓名"])
        ws.append([r["学号"], name, speak, focus, coop, disc, task])
    style_head(ws, 7)
    wb.save(path)


