def style_head(ws, ncol):
    for c in range(1, ncol + 1):
        cell = ws.cell(row=1, column=c)
        cell.font = Font(bold=True)
        cell.fill = HEAD_FILL
        cell.alignment = Alignment(horizontal="center", vertical="center")
    ws.freeze_panes = "A2"
    for i in range(1, ncol + 1):
        ws.column_dimensions[ws.cell(row=1, column=i).column_letter].width = 14


def clamp(v, lo, hi):
    return max(lo, min(hi, v))


def build_scores(rng):
    rows = []
    for sid, name, sex, level, mod in STUDENTS:
        scores = {}
        for sub in SUBJECTS:
            v = 55 + level + mod.get(sub, 0) + rng.uniform(-3.5, 3.5)
            scores[sub] = int(round(clamp(v, 41, 99)))
        for sub in ABSTENTION.get(sid, []):
            scores[sub] = None  # 缺考：不计 0 分
        total = sum(v for v in scores.values() if v is not None)
        mid = int(round(clamp(total + rng.uniform(-16, 16), 170, 396)))
        rows.append({"学号": sid, "姓名": name, "性别": sex, "分": scores,
                     "总分": total, "期中总分": mid})
    for key, field in (("总分", "班级排名"), ("期中总分", "期中排名")):
        order = sorted(rows, key=lambda r: -r[key])
        for i, r in enumerate(order, 1):
            r[field] = i
    return rows


